def _process_single_match(
    api_base: str,
    match_id: int,
    matches_info: dict
) -> Optional[dict]:

    try:

        target_team = matches_info.get(
            'target_team_name'
        )

        home_team = matches_info[
            match_id
        ]['homeTeam']

        away_team = matches_info[
            match_id
        ]['awayTeam']

        value_key = (
            'awayValue'
            if target_team == away_team
            else 'homeValue'
        )

        match_stats = {
            'match_id': match_id,
            'home_team': home_team,
            'away_team': away_team
        }

        # ------------------------------------------------
        # LINEUPS
        # ------------------------------------------------
        lineup_json = safe_get_json(
            api_base +
            f'events/{match_id}/lineups'
        )

        if lineup_json:

            side = (
                'home'
                if target_team == home_team
                else 'away'
            )

            match_stats['team_formation'] = (
                lineup_json
                .get(side, {})
                .get('formation')
            )

        # ------------------------------------------------
        # STATISTICS
        # ------------------------------------------------
        stats_json = safe_get_json(
            api_base +
            f'events/{match_id}/statistics'
        )

        if stats_json:

            stats_resp = stats_json.get(
                'statistics',
                []
            )

            for period in stats_resp:

                if period.get('period') == 'ALL':

                    for group in period.get(
                        'groups',
                        []
                    ):

                        for item in group.get(
                            'statisticsItems',
                            []
                        ):

                            if item.get('name'):

                                match_stats[
                                    item['name']
                                ] = item.get(value_key)

                    break

        # Small cooldown for API stability
        time.sleep(0.2)

        return match_stats

    except Exception as e:

        print(
            f"Match {match_id} error: {e}"
        )

        return None


