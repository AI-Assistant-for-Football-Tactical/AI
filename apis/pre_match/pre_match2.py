def get_training_player_stats(api_base: str, matches_info: dict) -> pd.DataFrame:
    """Gets player stats using the same logic as analyze_opponent_comprehensive_multimatch."""

    target_team = matches_info.get('target_team_name')
    if not target_team:
        return pd.DataFrame()

    match_ids = [k for k in matches_info.keys() if isinstance(k, int)]

    player_stats_agg = {}
    lock = Lock()

    # ── Helpers ───────────────────────────────────────────────────────────────
    def infer_role(p_role, heatmap):
        if not heatmap:
            return p_role

        right_pts  = sum(1 for pt in heatmap if pt['y'] < 25)
        center_pts = sum(1 for pt in heatmap if 25 <= pt['y'] <= 75)
        left_pts   = sum(1 for pt in heatmap if pt['y'] > 75)

        if right_pts + center_pts + left_pts == 0:
            return p_role

        x_coords      = [pt['x'] for pt in heatmap]
        avg_x         = sum(x_coords) / len(x_coords) if x_coords else 50
        zones         = {'Right': right_pts, 'Center': center_pts, 'Left': left_pts}
        dominant_zone = max(zones, key=zones.get)

        if p_role == 'G': return 'G'
        if p_role == 'D': return {'Right': 'RB', 'Left': 'LB'}.get(dominant_zone, 'CB')
        if p_role == 'M':
            if dominant_zone == 'Right': return 'RM'
            if dominant_zone == 'Left':  return 'LM'
            if avg_x < 45:              return 'CDM'
            if avg_x > 65:              return 'CAM'
            return 'CM'
        if p_role == 'F':
            return {'Right': 'RW', 'Left': 'LW'}.get(dominant_zone, 'ST')

        return p_role

    # ── Level 2 — one player ─────────────────────────────────────────────────
    def process_player(match_id, p):
        pid    = str(p['player']['id'])
        pname  = p['player']['name']
        p_role = p.get('position', 'M')

        p_stats = p.get('statistics', {})
        goals   = int(p_stats.get('goals', 0))
        assists = int(p_stats.get('goalAssist', 0))
        shots   = int(p_stats.get('totalShots', 0))
        try:    rating = float(p_stats.get('rating', 0))
        except: rating = 0.0

        match_role = p_role
        try:
            hm_resp = requests.get(
                api_base + f'events/{match_id}/player/{pid}/heatmap',
                timeout=(5, 15)
            )
            if hm_resp.status_code == 200:
                match_role = infer_role(p_role, hm_resp.json().get('heatmap', []))
        except Exception:
            pass

        with lock:
            if pid not in player_stats_agg:
                player_stats_agg[pid] = {
                    'name': pname,
                    'goals': 0, 'assists': 0, 'shots': 0,
                    'rating_sum': 0, 'rating_count': 0, 'match_count': 0,
                    'roles': set(), 'roles_played': set()
                }
            agg = player_stats_agg[pid]
            agg['goals']       += goals
            agg['assists']     += assists
            agg['shots']       += shots
            agg['match_count'] += 1
            agg['roles'].add(p_role)
            agg['roles_played'].add(match_role)
            if rating > 0:
                agg['rating_sum']   += rating
                agg['rating_count'] += 1

    # ── Level 1 — one match ──────────────────────────────────────────────────
    def process_match(match_id):
        match_meta     = matches_info.get(match_id, {})
        home_team_name = match_meta.get('homeTeam')
        side           = 'home' if home_team_name == target_team else 'away'

        try:
            lineups_resp = requests.get(
                api_base + f'events/{match_id}/lineups',
                timeout=(5, 15)
            )
            if lineups_resp.status_code != 200:
                return

            players = lineups_resp.json().get(side, {}).get('players', [])
            if not players:
                return

            with ThreadPoolExecutor(max_workers=10) as player_pool:
                futures = [player_pool.submit(process_player, match_id, p) for p in players]
                for f in as_completed(futures):
                    f.result()

        except Exception as e:
            print(f"Lineup error match {match_id}: {e}")

    # ── Run all matches concurrently ──────────────────────────────────────────
    with ThreadPoolExecutor(max_workers=5) as match_pool:
        futures = {match_pool.submit(process_match, mid): mid for mid in match_ids}
        for f in as_completed(futures):
            try:
                f.result()
            except Exception as e:
                print(f"Match error: {e}")

    # ── Build DataFrame ───────────────────────────────────────────────────────
    scored_players = []
    for pid, data in player_stats_agg.items():
        if data['match_count'] == 0:
            continue

        avg_rating       = data['rating_sum'] / data['rating_count'] if data['rating_count'] > 0 else 0
        detailed_roles   = sorted(data['roles_played']) if data['roles_played'] else list(data['roles'])
        goals_per_game   = data['goals']   / data['match_count']
        assists_per_game = data['assists'] / data['match_count']
        shots_per_game   = data['shots']   / data['match_count']
        threat_score     = (avg_rating * 1.5) + (goals_per_game * 10.0) + (assists_per_game * 8.0) + (shots_per_game * 0.5)

        scored_players.append({
            "Player ID":      pid,
            "Player Name":    data['name'],
            "Positions":      detailed_roles,
            "Matches Played": data['match_count'],
            "Mean Goals":     round(goals_per_game,   2),
            "Mean Assists":   round(assists_per_game, 2),
            "Mean Shots":     round(shots_per_game,   2),
            "Average Rating": round(avg_rating,       1),
            "Threat Score":   round(threat_score,     1)
        })

    return pd.DataFrame(scored_players)

